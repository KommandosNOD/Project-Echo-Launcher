local function reloadTranslations()
    local text = ViewpointUI.Text
    for k, fallback in pairs(defaults) do text[k] = localize(k, fallback) end
    if getTextOrNull then
        for ours, key in pairs(GAME_KEYS) do
            local v = getTextOrNull(key)
            if v and v ~= "" then text[ours] = v end
        end
    end
end

reloadTranslations()
Events.OnGameBoot.Add(reloadTranslations)
