local function localize(k, fallback)
    local translationKey = "UI_ProjectEcho_VPUI_" .. k
    local value = getText and getText(translationKey) or nil
    if not value or value == "" or value == translationKey then
        value = fallback
    else
        local fs = formats[k]
        if fs then
            for i = 1, #fs do
                local marker = "@@ECHO_FMT_" .. tostring(i) .. "@@"
                value = string.gsub(value, marker, function() return fs[i] end)
            end
        end
        value = string.gsub(value, "@@ECHO_PERCENT@@", function() return "%%" end)
    end
    return value
end

