-- Cache native translations only after the game's translation system has initialized.
R.cache = {}
local function nativeText(key)
    local cached = R.cache[key]
    if cached then return cached end
    if not getText then return nil end
    local ok, value = pcall(getText, key)
    if not ok or type(value) ~= "string" or value == key then return nil end
    R.cache[key] = value
    return value
end

function R.translate(input)
    if type(input) ~= "string" then return input end
    local key = R.exact[input]
    if key then
        local translated = nativeText(key)
        if translated then return translated end
        return input  -- Missing locale: readable English rather than a translation key.
    end
    -- The original game displays some dialogue options with a leading number.
    local lead, body = string.match(input, "^(%d+%.%s+)(.+)$")
    if lead then
        local translated = R.translate(body)
        if translated ~= body then return lead .. translated end
    end
    -- Dynamic mission hints: English captures are preserved, translated template from getText().
    for _, rule in ipairs(R.templates) do
        local cap = { string.match(input, rule.pattern) }
        if cap[1] ~= nil then
            local format = nativeText(rule.key)
            if format then
                return (string.gsub(format, "@@CAPTURE(%d+)@@", function(n)
                    return cap[tonumber(n)] or ""
                end))
            end
            return input
        end
    end
    return input
end
return R
