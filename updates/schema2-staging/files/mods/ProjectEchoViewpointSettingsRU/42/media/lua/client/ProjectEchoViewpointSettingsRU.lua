local function trans(value)
    if type(value) ~= "string" then return value end
    local key = words[value] or tooltipWords[value]
    if not key then return value end
    local result = getText(key)
    if not result or result == key then return value end
    return result
end

local function apply()
    if not (PZAPI and PZAPI.ModOptions and PZAPI.ModOptions.Data) then return end
    -- Do not translate pages on an English-language client.
    if getText("UI_PE_VPRU_MARKER") ~= "pe-vpru-ru" then return end
    local modified = 0
    for _, page in ipairs(PZAPI.ModOptions.Data) do
        if page and target[page.modOptionsID] then
            if type(page.name) == "string" then
                local result = trans(page.name)
                if result ~= page.name then page.name = result; modified = modified + 1 end
            end
            if type(page.data) == "table" then
                for _, item in ipairs(page.data) do
                    if type(item) == "table" then
                        for _, field in ipairs({"name", "text", "tooltip"}) do
                            if type(item[field]) == "string" then
                                local result = trans(item[field])
                                if result ~= item[field] then
                                    item[field] = result
                                    modified = modified + 1
                                end
                            end
                        end
                        if item.type == "combobox" and type(item.values) == "table" then
                            for i, value in ipairs(item.values) do
                                local result = trans(value)
                                if result ~= value then item.values[i] = result; modified = modified + 1 end
                            end
                        end
                    end
                end
            end
        end
    end
    if modified > 0 then print("[PE-VP-RU] Localized " .. tostring(modified) .. " Viewpoint labels/tooltips") end
end

-- No overrides of ISChat, keyboard handlers, options callbacks or per-frame HUD.
-- Delayed registration by other mods is handled by a short startup sweep.
local scans = 0
local watching = false
local function onTick()
    scans = scans + 1
    if scans % 15 == 1 then apply() end
    if scans >= 600 then
        Events.OnTick.Remove(onTick)
        watching = false
    end
end
local function startWatch()
    if watching or not (Events and Events.OnTick) then return end
    scans = 0
    watching = true
    Events.OnTick.Add(onTick)
end
local function refresh()
    apply()
    startWatch()
end
refresh()
if Events then
    if Events.OnMainMenuEnter then Events.OnMainMenuEnter.Add(refresh) end
    if Events.OnGameStart then Events.OnGameStart.Add(refresh) end
end
